export const supportedLanguages = [
  { code: 'en', name: 'English', nativeName: 'English' },
  { code: 'es', name: 'Spanish', nativeName: 'Español' },
  { code: 'fr', name: 'French', nativeName: 'Français' },
  { code: 'de', name: 'German', nativeName: 'Deutsch' },
  { code: 'ja', name: 'Japanese', nativeName: '日本語' },
];

export const i18n = {
  currentLanguage: 'en',

  init(language = 'en') {
    this.currentLanguage = language || 'en';
    const htmlLang = document.documentElement;
    if (htmlLang) htmlLang.setAttribute('lang', this.currentLanguage);
  },

  setLanguage(language) {
    if (!translations[language]) {
      console.warn(`Language ${language} not supported, falling back to en`);
      language = 'en';
    }
    this.currentLanguage = language;
    const htmlLang = document.documentElement;
    if (htmlLang) htmlLang.setAttribute('lang', language);
  },

  t(key, params = {}) {
    const segments = key.split('.');
    let value = translations[this.currentLanguage];
    for (const segment of segments) {
      if (value && typeof value === 'object') {
        value = value[segment];
      } else {
        value = undefined;
        break;
      }
    }

    if (value === undefined) {
      // Fall back to English
      value = translations.en;
      for (const segment of segments) {
        if (value && typeof value === 'object') {
          value = value[segment];
        } else {
          value = key;
          break;
        }
      }
    }

    if (typeof value !== 'string') return key;

    // Simple template replacement: {{key}}
    return value.replace(/\{\{(\w+)\}\}/g, (match, paramKey) => {
      return params[paramKey] !== undefined ? params[paramKey] : match;
    });
  },

  getSupportedLanguages() {
    return supportedLanguages;
  },
};

export default i18n;
